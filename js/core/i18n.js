  function detectLanguage(tag) {
    return String(tag || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
  }

  function fill(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (m, name) => (params[name] == null ? m : String(params[name])));
  }

  function translate(lang, key, params) {
    const dict = STRINGS[lang] || STRINGS.en;
    let text;
    if (params && params.count === 1 && dict[key + '.one'] != null) text = dict[key + '.one'];
    else if (dict[key] != null) text = dict[key];
    else if (STRINGS.en[key] != null) text = STRINGS.en[key];
    else return key;
    return fill(text, params);
  }

  return { LANGS, STRINGS, detectLanguage, translate };
